export const GLYPH_W = 5, GLYPH_H = 7;

/** Draw text into an RGBA buffer. Unknown characters become a solid block. */
export function drawText(
  data: Uint8Array | Uint8ClampedArray, imgW: number, imgH: number,
  text: string, x0: number, y0: number,
  rgb: [number, number, number] = [200, 205, 214], scale = 1,
): void {
  let cx = x0;
  for (const raw of text.toUpperCase()) {
    const rows = (GLYPHS[raw] ?? '11111/10001/10001/10001/10001/10001/11111').split('/');
    for (let ry = 0; ry < GLYPH_H; ry++) {
      for (let rx = 0; rx < GLYPH_W; rx++) {
        if (rows[ry][rx] !== '1') continue;
        for (let sy = 0; sy < scale; sy++) {
          for (let sx = 0; sx < scale; sx++) {
            const px = cx + rx * scale + sx, py = y0 + ry * scale + sy;
            if (px < 0 || py < 0 || px >= imgW || py >= imgH) continue;
            const i = (py * imgW + px) * 4;
            data[i] = rgb[0]; data[i + 1] = rgb[1]; data[i + 2] = rgb[2]; data[i + 3] = 255;
          }
        }
      }
    }
    cx += (GLYPH_W + 1) * scale;
  }
}

/** Break a line so it fits a pixel width. */
export function wrap(text: string, maxPx: number, scale = 1): string[] {
  const per = (GLYPH_W + 1) * scale;
  const max = Math.max(4, Math.floor(maxPx / per));
  const words = text.split(/\s+/);
  const lines: string[] = [];
  let cur = '';
  for (const w of words) {
    const candidate = cur ? `${cur} ${w}` : w;
    if (candidate.length <= max) { cur = candidate; continue; }
    if (cur) lines.push(cur);
    cur = w.length > max ? w.slice(0, max - 1) + '>' : w;
  }
  if (cur) lines.push(cur);
  return lines.slice(0, 3);
}
